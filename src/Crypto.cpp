bool Crypto_selfTest() {
  uint8_t h[32], o[32], t[16];
  for (size_t i = 0; i < sizeof(SHA_V) / sizeof(SHA_V[0]); i++) {
    Crypto_sha256((const uint8_t *)SHA_V[i].msg, SHA_V[i].len, h);
    if (!Crypto_equal(h, SHA_V[i].h, 32)) return false;
  }
  for (size_t i = 0; i < sizeof(X_V) / sizeof(X_V[0]); i++) {
    Crypto_x25519(o, X_V[i].s, X_V[i].u);
    if (!Crypto_equal(o, X_V[i].r, 32)) return false;
  }
  Crypto_x25519Base(o, DH_A);  if (!Crypto_equal(o, DH_PA, 32)) return false;
  Crypto_x25519Base(o, DH_B);  if (!Crypto_equal(o, DH_PB, 32)) return false;
  Crypto_x25519(o, DH_A, DH_PB); if (!Crypto_equal(o, DH_S, 32)) return false;
  Crypto_x25519(o, DH_B, DH_PA); if (!Crypto_equal(o, DH_S, 32)) return false;
  for (size_t i = 0; i < sizeof(CM_V) / sizeof(CM_V[0]); i++) {
    Crypto_aesCmac(CM_KEY, CM_MSG, CM_V[i].len, t);
    if (!Crypto_equal(t, CM_V[i].t, 16)) return false;
  }
  return true;
}
