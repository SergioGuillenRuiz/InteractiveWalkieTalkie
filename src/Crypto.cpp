#define ROR(x, n) (((x) >> (n)) | ((x) << (32 - (n))))

static void sha256Block(uint32_t h[8], const uint8_t *p) {
  uint32_t w[64];
  for (int i = 0; i < 16; i++)
    w[i] = ((uint32_t)p[4*i] << 24) | ((uint32_t)p[4*i+1] << 16) | ((uint32_t)p[4*i+2] << 8) | p[4*i+3];
  for (int i = 16; i < 64; i++) {
    uint32_t s0 = ROR(w[i-15], 7) ^ ROR(w[i-15], 18) ^ (w[i-15] >> 3);
    uint32_t s1 = ROR(w[i-2], 17) ^ ROR(w[i-2], 19) ^ (w[i-2] >> 10);
    w[i] = w[i-16] + s0 + w[i-7] + s1;
  }
  uint32_t a = h[0], b = h[1], c = h[2], d = h[3], e = h[4], f = h[5], g = h[6], hh = h[7];
  for (int i = 0; i < 64; i++) {
    uint32_t S1 = ROR(e, 6) ^ ROR(e, 11) ^ ROR(e, 25);
    uint32_t ch = (e & f) ^ (~e & g);
    uint32_t t1 = hh + S1 + ch + K256[i] + w[i];
    uint32_t S0 = ROR(a, 2) ^ ROR(a, 13) ^ ROR(a, 22);
    uint32_t mj = (a & b) ^ (a & c) ^ (b & c);
    uint32_t t2 = S0 + mj;
    hh = g; g = f; f = e; e = d + t1; d = c; c = b; b = a; a = t1 + t2;
  }
  h[0] += a; h[1] += b; h[2] += c; h[3] += d; h[4] += e; h[5] += f; h[6] += g; h[7] += hh;
}

void Crypto_sha256(const uint8_t *data, size_t len, uint8_t out[32]) {
  uint32_t h[8] = { 0x6a09e667,0xbb67ae85,0x3c6ef372,0xa54ff53a,0x510e527f,0x9b05688c,0x1f83d9ab,0x5be0cd19 };
  size_t i = 0;
  for (; i + 64 <= len; i += 64) sha256Block(h, data + i);
  uint8_t tail[128];
  size_t rem = len - i;
  memcpy(tail, data + i, rem);
  tail[rem++] = 0x80;
  size_t total = (rem + 8 <= 64) ? 64 : 128;
  memset(tail + rem, 0, total - rem);
  uint64_t bits = (uint64_t)len * 8;
  for (int k = 0; k < 8; k++) tail[total - 1 - k] = (uint8_t)(bits >> (8 * k));
  sha256Block(h, tail);
  if (total == 128) sha256Block(h, tail + 64);
  for (int k = 0; k < 8; k++) {
    out[4*k] = h[k] >> 24; out[4*k+1] = h[k] >> 16; out[4*k+2] = h[k] >> 8; out[4*k+3] = h[k];
  }
}

// ============================================================
//  X25519 (TweetNaCl, dominio publico). Aritmetica de campo en 16 "limbs" de 16 bits con enteros de 64 bits.
// ============================================================
typedef int64_t gf[16];
static const gf C121665 = { 0xDB41, 1 };

static void car25519(gf o) {
  for (int i = 0; i < 16; i++) {
    o[i] += (1LL << 16);
    int64_t c = o[i] >> 16;
    o[(i + 1) * (i < 15)] += c - 1 + 37 * (c - 1) * (i == 15);
    o[i] -= c << 16;
  }
}
static void sel25519(gf p, gf q, int64_t b) {
  int64_t c = ~(b - 1);
  for (int i = 0; i < 16; i++) { int64_t t = c & (p[i] ^ q[i]); p[i] ^= t; q[i] ^= t; }
}
static void pack25519(uint8_t *o, const gf n) {
  gf m, t;
  for (int i = 0; i < 16; i++) t[i] = n[i];
  car25519(t); car25519(t); car25519(t);
  for (int j = 0; j < 2; j++) {
    m[0] = t[0] - 0xffed;
    for (int i = 1; i < 15; i++) { m[i] = t[i] - 0xffff - ((m[i-1] >> 16) & 1); m[i-1] &= 0xffff; }
    m[15] = t[15] - 0x7fff - ((m[14] >> 16) & 1);
    int64_t b = (m[15] >> 16) & 1;
    m[14] &= 0xffff;
    sel25519(t, m, 1 - b);
  }
  for (int i = 0; i < 16; i++) { o[2*i] = t[i] & 0xff; o[2*i+1] = t[i] >> 8; }
}
static void unpack25519(gf o, const uint8_t *n) {
  for (int i = 0; i < 16; i++) o[i] = n[2*i] + ((int64_t)n[2*i+1] << 8);
  o[15] &= 0x7fff;
}
static void fA(gf o, const gf a, const gf b) { for (int i = 0; i < 16; i++) o[i] = a[i] + b[i]; }
static void fZ(gf o, const gf a, const gf b) { for (int i = 0; i < 16; i++) o[i] = a[i] - b[i]; }
static void fM(gf o, const gf a, const gf b) {
  int64_t t[31];
  for (int i = 0; i < 31; i++) t[i] = 0;
  for (int i = 0; i < 16; i++) for (int j = 0; j < 16; j++) t[i+j] += a[i] * b[j];
  for (int i = 0; i < 15; i++) t[i] += 38 * t[i+16];
  for (int i = 0; i < 16; i++) o[i] = t[i];
  car25519(o); car25519(o);
}
static void fS(gf o, const gf a) { fM(o, a, a); }
static void inv25519(gf o, const gf in) {
  gf c;
  for (int a = 0; a < 16; a++) c[a] = in[a];
  for (int a = 253; a >= 0; a--) { fS(c, c); if (a != 2 && a != 4) fM(c, c, in); }
  for (int a = 0; a < 16; a++) o[a] = c[a];
}

void Crypto_x25519(uint8_t out[32], const uint8_t scalar[32], const uint8_t point[32]) {
  uint8_t z[32];
  int64_t x[80];
  gf a, b, c, d, e, f;
  for (int i = 0; i < 31; i++) z[i] = scalar[i];
  z[31] = (scalar[31] & 127) | 64;
  z[0] &= 248;
  unpack25519(x, point);
  for (int i = 0; i < 16; i++) { b[i] = x[i]; d[i] = a[i] = c[i] = 0; }
  a[0] = d[0] = 1;
  for (int i = 254; i >= 0; --i) {
    int64_t r = (z[i >> 3] >> (i & 7)) & 1;
    sel25519(a, b, r); sel25519(c, d, r);
    fA(e, a, c); fZ(a, a, c); fA(c, b, d); fZ(b, b, d);
    fS(d, e); fS(f, a); fM(a, c, a); fM(c, b, e);
    fA(e, a, c); fZ(a, a, c); fS(b, a); fZ(c, d, f);
    fM(a, c, C121665); fA(a, a, d); fM(c, c, a); fM(a, d, f);
    fM(d, b, x); fS(b, e);
    sel25519(a, b, r); sel25519(c, d, r);
    yield();                                   // ~4 ms por vuelta en el ESP8266: no dejar que salte el watchdog
  }
  for (int i = 0; i < 16; i++) { x[i+16] = a[i]; x[i+32] = c[i]; x[i+48] = b[i]; x[i+64] = d[i]; }
  inv25519(x + 32, x + 32);
  fM(x + 16, x + 16, x + 32);
  pack25519(out, x + 16);
}

void Crypto_x25519Base(uint8_t out[32], const uint8_t scalar[32]) {
  uint8_t base[32] = { 9 };
  Crypto_x25519(out, scalar, base);
}

// ============================================================
//  AES-CMAC (RFC 4493)
// ============================================================
static void aesEnc(const uint8_t key[16], uint8_t blk[16]) {
  struct AES_ctx ctx;
  AES_init_ctx(&ctx, key);
  AES_ECB_encrypt(&ctx, blk);
}
static void dbl(uint8_t b[16]) {
  uint8_t carry = b[0] >> 7;
  for (int i = 0; i < 15; i++) b[i] = (b[i] << 1) | (b[i+1] >> 7);
  b[15] = (b[15] << 1) ^ (carry ? 0x87 : 0);
}

void Crypto_aesCmac(const uint8_t key[16], const uint8_t *msg, size_t len, uint8_t out[16]) {
  uint8_t k1[16] = {0};
  aesEnc(key, k1);
  dbl(k1);
  uint8_t k2[16]; memcpy(k2, k1, 16); dbl(k2);
  size_t n = (len + 15) / 16;
  bool complete = (len > 0 && len % 16 == 0);
  if (n == 0) n = 1;
  uint8_t x[16] = {0}, last[16];
  for (size_t i = 0; i + 1 < n; i++) {
    for (int j = 0; j < 16; j++) x[j] ^= msg[16*i + j];
    aesEnc(key, x);
  }
  size_t off = 16 * (n - 1), rem = len - off;
  if (complete) { for (int j = 0; j < 16; j++) last[j] = msg[off + j] ^ k1[j]; }
  else {
    memset(last, 0, 16);
    memcpy(last, msg + off, rem);
    last[rem] = 0x80;
    for (int j = 0; j < 16; j++) last[j] ^= k2[j];
  }
  for (int j = 0; j < 16; j++) x[j] ^= last[j];
  aesEnc(key, x);
  memcpy(out, x, 16);
}

bool Crypto_equal(const uint8_t *a, const uint8_t *b, size_t n) {
  uint8_t d = 0;
  for (size_t i = 0; i < n; i++) d |= a[i] ^ b[i];
  return d == 0;
}

